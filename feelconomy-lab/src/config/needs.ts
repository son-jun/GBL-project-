/**
 * 감성욕구(需求) 축 설정 — 새 설계의 핵심 변수.
 *
 * ============================================================================
 *  설계 변경 안내 (v2)
 * ============================================================================
 * 기존 v1은 "감정 상태" 10개(기쁨·스트레스 등)를 참가자 다수의 기준 데이터셋과
 * 비교하는 방식이었다. 이 방식은 "첫 참가자는 혼자 계산할 수 없다"는 근본적인
 * 문제가 있었다 — 한 사람의 감정벡터 1개만으로는 rank 1짜리 데이터라 SVD가
 * 의미를 갖지 못한다.
 *
 * v2는 이 문제를 "감정 상태"가 아니라 "감성욕구(需求)"로 바꾸고, 참가자 한 명이
 * 스스로 [소비대안 × 감성욕구] 평가행렬을 만들게 하여 해결한다. 이제 SVD는
 * "이 사람이 여러 소비를 평가할 때 반복적으로 나타나는 욕구의 결합"을 찾는
 * 역할을 하고, 첫 번째 참가자부터 자기 데이터만으로 완결된 분석이 가능하다.
 *
 * 따라서 이 프로젝트에는 더 이상 "기준 데이터셋"이나 "사전 학습 모델"이
 * 존재하지 않는다. 실제 데이터든 합성 데이터든 어떤 참가자 집단 데이터도
 * 미리 준비할 필요가 없다 — 모든 참가자가 자기 자신의 데이터만으로 SVD와
 * K-means를 완결한다.
 */

export interface NeedAxis {
  /** 안정적인 키 (CSV 컬럼·저장소 컬럼에 쓰인다) */
  key: string
  /** 화면에 보이는 이름 */
  label: string
  /** 참가자용 짧은 도움말 */
  hint: string
  /**
   * 이 욕구가 지배적인 소비대안 군집에 자동으로 이름을 붙일 때 쓰는 짧은 이름.
   * (요구사항: 군집 이름을 시스템이 "확정 연구 결과"인 것처럼 지어서는 안 되지만,
   *  이 게임에서는 매 참가자마다 그 사람만의 군집이 실시간으로 만들어지므로
   *  연구자가 사후에 일일이 이름 붙일 수 없다. 대신 군집을 이루는 소비대안들이
   *  평균적으로 어떤 욕구를 가장 크게 충족하는지를 기준으로 즉석에서 이름을
   *  구성한다 — 이것은 "경험적 데이터를 과장 해석하는 것"이 아니라 게임의
   *  안내 문구를 만드는 규칙일 뿐임을 결과 화면에서 함께 설명한다.)
   */
  archetypeLabel: string
}

