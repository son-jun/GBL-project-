/**
 * 분석 스펙 설정 (v2).
 *
 * ============================================================================
 *  v1과의 결정적 차이
 * ============================================================================
 * v1: "기준 데이터셋으로 평균·SVD축·군집중심을 미리 학습 → 고정 모델 버전 →
 *      새 참가자는 그 모델에 투영만 한다." 관리자가 CSV를 올려 모델을 "학습"
 *      시키는 절차가 있었다.
 *
 * v2: 학습이라는 절차 자체가 없다. 참가자 한 명의 [소비대안 × 감성욕구]
 *     평가행렬이 그 사람의 SVD 입력 전부이고, 군집도 그 사람의 소비대안
 *     평가만으로 그 자리에서 만들어진다. 그래서 "모델을 사전에 준비해야
 *     참가자가 결과를 볼 수 있다"는 제약이 사라졌다 — 첫 번째 참가자도
 *     자기 데이터만으로 처음부터 끝까지 계산이 끝난다.
 *
 * 아래 값들은 "학습되는 값"이 아니라 "모든 참가자에게 동일하게 적용되는
 * 계산 규�다" 자체다. 그래서 이름도 model이 아니라 SPEC(분석 규격)이라고
 * 부른다. SPEC_VERSION은 이 규칙 묶음(축 정의·K·r 기본값)의 버전 표시이며,
 * 참가자 결과에 항상 함께 기록되어 "이 결과는 어떤 규칙으로 계산되었는가"를
 * 재현할 수 있게 한다.
 */

import { ALTERNATIVE_DIM } from './alternatives'
import { NEED_DIM } from './needs'

/**
 * 참가자가 평가 화면에서 눌러야 하는 칸 수 (= 평가행렬 A의 원소 개수).
 * 화면 문구에서 "○○개 점수"를 쓸 때 숫자를 직접 적지 말고 이 값을 쓴다 —
 * 대안·욕구 개수를 바꿨을 때 문구가 실제와 어긋나는 것을 막는다.
 */
export const RATING_CELL_COUNT = ALTERNATIVE_DIM * NEED_DIM

/** 활동 전체에서 참가자가 입력하는 총 문항 수 (감성욕구 + 평가행렬) */
export const TOTAL_INPUT_COUNT = NEED_DIM + RATING_CELL_COUNT

export const ANALYSIS_SPEC = {
  /**
   * 이 분석 규격의 버전. 축·K·r 기본값을 바꾸면 버전을 올린다.
   *
   * V3: 소비대안을 8개 → 6개로 줄였다. 평가행렬의 모양(8×6 → 6×6)이
   *     바뀌었으므로, V2로 기록된 과거 참가자 데이터와는 좌표를 직접
   *     비교할 수 없다. 그래서 규격 버전을 올려 구분한다.
   */
  version: 'FEELCONOMY-INDIV-V3',

  /**
   * 잠재 차원 r의 기본 제안값과 참가자가 고를 수 있는 범위.
   * 요구사항: "특이값 누적 설명비율을 보고 r=2 또는 3 선택"
   * → 참가자가 자신의 설명분산 표를 보고 직접 고르게 한다 (게임 요소).
   */
  defaultLatentDim: 2,
  latentDimChoices: [2, 3] as const,

  /**
   * 소비대안을 나눌 군집 개수 K.
   * 소비대안이 6개뿐이므로 K가 너무 크면 군집 하나에 대안이 1개만 남아
   * 의미가 옅어진다. K=3이면 군집당 평균 2개로, 이것이 하한선이다.
   * (v2에서는 대안이 8개였고 kMax가 4였다. 대안이 6개로 줄었으므로
   *  상한도 3으로 함께 내렸다 — K=4면 군집당 1.5개가 된다.)
   */
  defaultK: 3,
  kMin: 2,
  kMax: 3,

  /** k-means++ 초기화 반복 횟수. 대안이 6개뿐이라 계산은 순식간에 끝난다. */
  nInit: 50,
  maxIterations: 300,
  tolerance: 1e-9,

  /** 시드 고정 — 같은 입력이면 항상 같은 군집 결과가 나오게 한다 */
  randomSeed: 20260814,
} as const

export const MAX_LATENT_DIM = 3

/**
 * 손계산 비교 기능(요구사항 §14)에서 쓰는 표시용 상수.
 * v2에서도 이 기능은 그대로 유지한다 — 참가자가 직접 계산한 좌표와
 * 프로그램 계산을 비교하는 것은 v1/v2 어느 쪽이든 동일하게 의미가 있다.
 */
export const HAND_CALC_TOLERANCE_GOOD = 0.05
export const HAND_CALC_TOLERANCE_OK = 0.5
